// Writes src/baked/xatlas.ts: the xatlas WebAssembly binary from the xatlas-wasm package,
// deflated and inlined as base64. Its own JS glue cannot ship: it holds a dynamic import (for Node),
// which .glts scripts reject, so src/baked/unwrap.ts instantiates the binary itself.
//
//   pnpm --filter @drawcall/lod xatlas
//
import { readFile, writeFile } from "node:fs/promises";
import { deflateSync } from "fflate";
import createXAtlas from "xatlas-wasm";

// Pinned in package.json: the binary changes only with a deliberate update.
const version: string = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8")).devDependencies["xatlas-wasm"];

// The glue decodes its inlined binary and hands it to WebAssembly.instantiate: take it there.
let binary: Uint8Array | undefined;
const instantiate = WebAssembly.instantiate;
Object.defineProperty(WebAssembly, "instantiate", {
  value: (bytes: unknown, imports: WebAssembly.Imports) => {
    if (!(bytes instanceof Uint8Array)) throw new Error("xatlas-wasm passed no Uint8Array to WebAssembly.instantiate");
    binary = bytes.slice();
    return instantiate(bytes, imports);
  },
});
await createXAtlas();
Object.defineProperty(WebAssembly, "instantiate", { value: instantiate });
if (!binary) throw new Error("xatlas-wasm did not instantiate a binary");

const deflated = deflateSync(binary, { level: 9 });

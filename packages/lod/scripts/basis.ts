// Writes src/impostor/ktx2/wasm/encoder.ts and transcoder.ts: Basis Universal's encoder (its Emscripten module and
// binary) from the ktx2-encoder package, and three's Basis transcoder (its JS wrapper and binary), each deflated and
// inlined as base64. A package's own files have no URL a pre-bundled dependency can fetch under Vite's dev server in a
// workspace, whose node_modules lie outside the served root, so the impostor codec carries them. Carrying the encoder's
// module as well leaves no bare import that only a cold cache reaches: a Vite dependency cache made without it finds it
// late and reloads the page, and a build would emit the package's own 3 MB binary.
//
//   pnpm --filter @drawcall/lod basis
//
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "fflate";

const manifest = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
// ktx2-encoder exports only its wrapper; the Emscripten module and its binary sit beside it.
const encoder = join(dirname(fileURLToPath(import.meta.resolve("ktx2-encoder"))), "../basis");
const transcoder = import.meta.resolve("three/examples/jsm/libs/basis/basis_transcoder.js");
const basis = dirname(fileURLToPath(transcoder));
const three: string = JSON.parse(await readFile(new URL("../../../../package.json", transcoder), "utf8")).version;

const NOTICE = `// Basis Universal, https://github.com/BinomialLLC/basis_universal
//   Copyright © 2016–2026 Binomial LLC. Licensed under the Apache License 2.0,
//   https://www.apache.org/licenses/LICENSE-2.0. "Basis Universal" is a trademark of Binomial LLC.`;

const deflate = (bytes: Uint8Array) => Buffer.from(deflateSync(bytes, { level: 9 })).toString("base64");
const inline = async (path: string) => deflate(await readFile(path));

// The encoder imports from a data: URL, in browsers and in Node, as a `vite build` warmup runs it. Emscripten's Node
// path needs a file: URL for createRequire, so the module takes its browser path everywhere: given its binary, it
// needs nothing else.
const NODE = `var ENVIRONMENT_IS_NODE=typeof process=="object"&&process.versions?.node&&process.type!="renderer";`;
const emscripten = await readFile(join(encoder, "basis_encoder.js"), "utf8");
if (!emscripten.includes(NODE)) throw new Error("basis_encoder.js no longer detects Node as scripts/basis.ts expects");

await write(
  "encoder.ts",
  `// Generated by scripts/basis.ts from ktx2-encoder ${manifest.devDependencies["ktx2-encoder"]}; do not edit.
//
${NOTICE}

/** Basis Universal's encoder as ktx2-encoder builds it: the Emscripten module (ES, its default export the factory,
 *  never taking its Node path) and the WebAssembly binary, deflated, as base64. */
export const ENCODER_JS = "${deflate(Buffer.from(emscripten.replace(NODE, "var ENVIRONMENT_IS_NODE=false;")))}";
export const ENCODER_WASM = "${await inline(join(encoder, "basis_encoder.wasm"))}";
`,
);
await write(
  "transcoder.ts",
  `// Generated by scripts/basis.ts from three ${three}; do not edit.
//
${NOTICE}

/** three's Basis transcoder for its KTX2Loader: the JS wrapper and the WebAssembly binary, deflated, as base64. */
export const TRANSCODER_JS = "${await inline(join(basis, "basis_transcoder.js"))}";
export const TRANSCODER_WASM = "${await inline(join(basis, "basis_transcoder.wasm"))}";
`,
);

async function write(name: string, source: string) {
  await writeFile(new URL(`../src/impostor/ktx2/wasm/${name}`, import.meta.url), source);
  console.log(`wrote src/impostor/ktx2/wasm/${name} (${source.length} bytes)`);
}

// Writes src/impostor/ktx2/wasm/encoder.ts and transcoder.ts: Basis Universal's encoder WebAssembly binary from the
// ktx2-encoder package, and three's Basis transcoder (its JS wrapper and binary), each deflated and inlined as base64.
// A package's own files have no URL a pre-bundled dependency can fetch under Vite's dev server in a workspace, whose
// node_modules lie outside the served root, so the impostor codec carries them. ktx2-encoder is pinned in package.json:
// its wrapper loads the binary inlined here, which must be the one its version ships.
//
//   pnpm --filter @drawcall/lod basis
//
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "fflate";

const manifest = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
// ktx2-encoder exports only its wrapper; its binary sits beside it.
const encoder = join(dirname(fileURLToPath(import.meta.resolve("ktx2-encoder"))), "../basis/basis_encoder.wasm");
const transcoder = import.meta.resolve("three/examples/jsm/libs/basis/basis_transcoder.js");
const basis = dirname(fileURLToPath(transcoder));
const three: string = JSON.parse(await readFile(new URL("../../../../package.json", transcoder), "utf8")).version;

const NOTICE = `// Basis Universal, https://github.com/BinomialLLC/basis_universal
//   Copyright © 2016–2026 Binomial LLC. Licensed under the Apache License 2.0,
//   https://www.apache.org/licenses/LICENSE-2.0. "Basis Universal" is a trademark of Binomial LLC.`;

const inline = async (path: string) => Buffer.from(deflateSync(await readFile(path), { level: 9 })).toString("base64");

await write(
  "encoder.ts",
  `// Generated by scripts/basis.ts from ktx2-encoder ${manifest.dependencies["ktx2-encoder"]}; do not edit.
//
${NOTICE}

/** Basis Universal's encoder WebAssembly binary, as ktx2-encoder builds it, deflated, as base64. */
export const ENCODER_WASM = "${await inline(encoder)}";
`,
);
await write(
  "transcoder.ts",
  `// Generated by scripts/basis.ts from three ${three}; do not edit.
//
${NOTICE}

/** three's Basis transcoder for its KTX2Loader: the JS wrapper and the WebAssembly binary, deflated, as base64. */
export const TRANSCODER_JS = "${await inline(join(basis, "basis_transcoder.js"))}";
export const TRANSCODER_WASM = "${await inline(join(basis, "basis_transcoder.wasm"))}";
`,
);

async function write(name: string, source: string) {
  await writeFile(new URL(`../src/impostor/ktx2/wasm/${name}`, import.meta.url), source);
  console.log(`wrote src/impostor/ktx2/wasm/${name} (${source.length} bytes)`);
}

import { encodeImpostor, toBase64 } from "./codec.js";
import type { Impostor } from "./impostor.js";

/** This package's version, pinned in the scripts it writes; a test keeps it equal to package.json. */
export const VERSION = "0.1.0";

/**
 * Source of a self-contained `.glts` script that renders `impostor` as one natively
 * instanced `ImpostorMesh`, with the atlas embedded as base64 KTX2.
 */
export function writeImpostorGlts(impostor: Impostor): string {
  const data = toBase64(encodeImpostor(impostor));
  const { layout, frames, size, maps } = impostor;
  return `// Octahedral impostor generated by @drawcall/impostor: ${layout} layout, ${frames}x${frames} frames, ${size}px atlas, maps ${maps.join(", ")}.
import { instanceCount, onDispose, onMatrixUpdateAt, scene } from "@drawcall/glts";
import { ImpostorMesh, decodeImpostor } from "@drawcall/impostor@${VERSION}";

const impostor = decodeImpostor("${data}");
const mesh = new ImpostorMesh(impostor, instanceCount);
scene.add(mesh);

onMatrixUpdateAt((index, matrix) => {
  mesh.setMatrixAt(index, matrix);
  mesh.instanceMatrix.needsUpdate = true;
  // InstancedMesh caches its bounds on first cull; drop them so moved instances are not culled.
  mesh.boundingBox = null;
  mesh.boundingSphere = null;
});

onDispose(() => mesh.dispose());
`;
}

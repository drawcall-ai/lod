import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { decodeImpostor } from "../src/codec.js";
import { VERSION, writeImpostorGlts } from "../src/glts.js";
import type { Impostor } from "../src/impostor.js";

const impostor: Impostor = {
  version: 1,
  layout: "full",
  frames: 4,
  size: 16,
  box: [-1, -1, -1, 1, 1, 1],
  halfSize: 1.8,
  maps: ["base", "normalDepth", "orm"],
  layers: [0, 1, 2].map((l) => new Uint8Array(16 * 16 * 4).map((_, i) => (i * 7 + l) & 255)),
};

const source = writeImpostorGlts(impostor);

/** The sibling glts checkout, whose real validation rules the script must pass. */
const glts = new URL("../../../../glts/packages/glts/src/modules/", import.meta.url);

describe("writeImpostorGlts", () => {
  it("VERSION matches package.json", () => {
    const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
    expect(VERSION).toBe(pkg.version);
  });

  it("writes the expected script", () => {
    const lines = source.split("\n");
    expect(lines[0]).toBe("// Octahedral impostor generated by @drawcall/impostor: full layout, 4x4 frames, 16px atlas, maps base, normalDepth, orm.");
    expect(lines[1]).toBe('import { instanceCount, onDispose, onMatrixUpdateAt, scene } from "@drawcall/glts";');
    expect(lines[2]).toBe(`import { ImpostorMesh, decodeImpostor } from "@drawcall/impostor@${VERSION}";`);
    expect(lines[4]).toMatch(/^const impostor = decodeImpostor\("[A-Za-z0-9+/]+=*"\);$/);
    expect(source).toContain("onDispose(() => mesh.dispose());");
    expect(source).not.toMatch(/^\s*export\b/m);
  });

  it("embeds a decodable impostor", () => {
    const base64 = /decodeImpostor\("([^"]+)"\)/.exec(source)![1]!;
    const back = decodeImpostor(base64);
    expect(back.maps).toEqual(impostor.maps);
    back.layers.forEach((layer, i) => expect(Buffer.compare(layer, impostor.layers[i]!)).toBe(0));
  });

  it("runs against a fake GLTS context", () => {
    const body = source.replace(/^import .*$/gm, "");
    const calls: string[] = [];
    let update: ((index: number, matrix: unknown) => void) | undefined;
    let dispose: (() => void) | undefined;
    class ImpostorMesh {
      instanceMatrix = { needsUpdate: false };
      constructor(readonly data: Impostor, readonly count: number) {}
      setMatrixAt(index: number) {
        calls.push(`set ${index}`);
      }
      dispose() {
        calls.push("dispose");
      }
    }
    const scene = { add: (mesh: ImpostorMesh) => calls.push(`add ${mesh.count} ${mesh.data.size}`) };
    const run = new Function("instanceCount", "onDispose", "onMatrixUpdateAt", "scene", "ImpostorMesh", "decodeImpostor", body);
    run(5, (f: () => void) => (dispose = f), (f: typeof update) => (update = f), scene, ImpostorMesh, decodeImpostor);
    update!(3, {});
    dispose!();
    expect(calls).toEqual(["add 5 16", "set 3", "dispose"]);
  });

  describe.skipIf(!existsSync(fileURLToPath(glts)))("GLTS rules", () => {
    it("passes the GLTS compiler and rewriter", async () => {
      const at = (file: string) => new URL(file, glts).href;
      const { compileScript } = await import(/* @vite-ignore */ at("compiler.ts"));
      const { rewriteModule } = await import(/* @vite-ignore */ at("rewrite.ts"));
      const url = "https://example.com/tree.glts";
      const compiled: string = compileScript(source, { url, importChain: [url] });
      const specifiers: string[] = [];
      await rewriteModule({
        source: compiled,
        sourceURL: url,
        importChain: [url],
        resolveImport: async (specifier: string) => (specifiers.push(specifier), specifier),
      });
      expect(specifiers).toEqual(["@drawcall/glts", `@drawcall/impostor@${VERSION}`]);
      expect(() => compileScript(`${source}\nexport {};`, { url, importChain: [url] })).toThrow(/must not export/);
    });
  });
});

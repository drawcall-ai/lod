import { encodeImpostor, type Impostor } from "@drawcall/lod";
import lod from "../../../packages/lod/package.json";

/**
 * Source of a self-contained `.glts` script that renders `impostor` as one natively
 * instanced `ImpostorMesh`, with the atlas embedded as base64 KTX2. It imports the
 * package at this checkout's version, which the lab's dev server serves (vite.config.ts).
 */
export function writeImpostorGlts(impostor: Impostor): string {
  const data = toBase64(encodeImpostor(impostor));
  const { layout, frames, size, maps } = impostor;
  return `// Octahedral impostor generated by @drawcall/lod: ${layout} layout, ${frames}x${frames} frames, ${size}px atlas, maps ${maps.join(", ")}.
import { instanceCount, onDispose, onMatrixUpdateAt, scene } from "@drawcall/glts";
import { ImpostorMesh, decodeImpostor } from "@drawcall/lod@${lod.version}";

const impostor = decodeImpostor("${data}");
const mesh = new ImpostorMesh(impostor, instanceCount);
scene.add(mesh);

onMatrixUpdateAt((index, matrix) => {
  mesh.setMatrixAt(index, matrix);
  mesh.instanceMatrix.needsUpdate = true;
  // InstancedMesh caches its bounds on first cull; drop them so moved instances are not culled.
  mesh.boundingBox = null;
  mesh.boundingSphere = null;
});

onDispose(() => mesh.dispose());
`;
}

/** Base64 of `bytes`, chunked so tens of megabytes do not overflow the stack. */
function toBase64(bytes: Uint8Array): string {
  const chunk = 3 * 0x3000; // a multiple of 3, so chunks concatenate without padding
  const parts: string[] = [];
  for (let i = 0; i < bytes.length; i += chunk) parts.push(btoa(String.fromCharCode(...bytes.subarray(i, i + chunk))));
  return parts.join("");
}

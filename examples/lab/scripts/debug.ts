// Render a debug comparison (normal | albedo) for a subject and view.
import { mkdir, writeFile } from "node:fs/promises";
import { chromium } from "@playwright/test";
import { createServer } from "vite";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const out = new URL("../../../.artifacts/debug/", import.meta.url);
await mkdir(out, { recursive: true });
const [name = "tree", what = "normal", px = "192", el = "12", az = "133", mesh = "{}", bake = "{}", fov = "30"] = process.argv.slice(2);
const server = await createServer({ root, logLevel: "error", server: { port: 5195 } });
await server.listen();
const browser = await chromium.launch({ headless: true, args: ["--use-angle=metal", "--enable-gpu", "--ignore-gpu-blocklist"] });
const page = await browser.newPage();
page.on("pageerror", (e) => console.error("[page]", e.message));
await page.goto(`${server.resolvedUrls!.local[0]}?auto`);
await page.waitForFunction(() => "lab" in window);
await page.evaluate(([n, m, b]) => (window as any).lab.prepare(n, JSON.parse(b), JSON.parse(m)), [name, mesh, bake] as const);
const r = await page.evaluate(([w, p, e, a, f]) => (window as any).lab.debugCompare({ px: +p, elevation: +e, azimuth: +a, fov: +f }, w), [what, px, el, az, fov] as const);
console.log(`${name} ${what} err ${r.error.toFixed(3)} bias ${(r.bias * 255).toFixed(1)}`);
await writeFile(new URL(`${name}-${what}-${px}-${el}-${az}-fov${fov}.png`, out), Buffer.from(r.image.split(",")[1], "base64"));
await browser.close();
await server.close();
